"""Writes results/phaseC/README.md tables from results/phaseC/*.json (called by 30_phaseC_metric.py --readme)."""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.config import RESULTS, SEEDS  # noqa: E402

OUT = RESULTS / "phaseC"
ORDER = ["ref_gls", "ref_best", "identity_cos", "identity_rowzso", "L1line_cos", "L1line_rowzso", "L1eig_cos",
         "L1eig_rowzso", "L2d32_cos", "L2d32_rowzso", "L2d64_cos", "L2d64_rowzso", "L2d128_cos", "L2d128_rowzso",
         "L2d32nce_cos", "L2d32nce_rowzso", "L2d64nce_cos", "L2d64nce_rowzso", "L2d128nce_cos", "L2d128nce_rowzso"]


def f3(x):
    return "—" if x is None or not np.isfinite(x) else f"{x:.3f}"


def load(name, seed):
    p = OUT / f"{name}_cluster_seed{seed}.json"
    return json.loads(p.read_text()) if p.exists() else None


def ci(d):
    return f"{d['diff']:+.3f} [{d['ci_low']:+.3f}, {d['ci_high']:+.3f}]" if d else "—"


def write_readme(extra_text: str | None = None):
    cmp = json.loads((OUT / "compare.json").read_text()) if (OUT / "compare.json").exists() else {"seeds": {}}
    s0 = cmp["seeds"].get(str(SEEDS[0]), {})
    L = ["# Phase C: supervised metric learning (dev cluster CV)", "",
         "Generated by `scripts/30_phaseC_metric.py --readme` (tables); code `src/metric_learning.py`, tests "
         "`tests/test_metric_learning.py`. DEV pairs only via `src/evaluate.run_dev_cv` (every run a logged trial); "
         "IFT never loaded. Per fold the learned map is fitted on that fold's training pairs only (λ and number of "
         "steps chosen by an inner cluster-grouped validation split of the training pairs; 0 steps = identity), then "
         "applied to all 18,434 genes. `cos` = first-order cosine of learned embeddings; `rowzso` = L3: genome-wide "
         "top-0.25% balanced-neighbour second-order cosine + genome-wide row-z on the learned embedding (identical "
         "pipeline to the Phase-A best). `identity_*` reproduce the Phase-A layers through the same code path.", "",
         "Columns: HT-AP fold mean ± sd (SEEDS[0], primary); pooled = HT-AP of pooled OOF predictions; no-top10 = "
         "pooled OOF HT-AP on pairs not touching the 10 clusters with most within-cluster OOF positives; macro = "
         "macro per-cluster AP (fold mean); strata = HT-AP fold means for both non-essential / mixed / both "
         "essential; Δ = paired cluster bootstrap (1,000) on pooled OOF, 95% CI; fit = mean training time per fold "
         "(inner λ search + refit); score = mean time per fold to embed all genes and score the test pairs "
         "(genome-wide neighbours + row moments for rowzso); steps = chosen training steps per fold.", "",
         "## Ladder (SEEDS[0])", "",
         "| scorer | HT-AP | pooled | no-top10 | macro | non-ess / mixed / ess | Δ vs best | Δ vs GLS | Δ vs best, no-top10 | "
         "fit s | score s | steps per fold |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name in ORDER:
        r = load(name, SEEDS[0])
        if r is None:
            continue
        s, pc = r["summary"], r.get("phaseC", {})
        po = pc.get("pooled_oof", {})
        fs = pc.get("fit_summary", [])
        fit = [f["fit_s"] for f in fs if f.get("fit_s") is not None and not f.get("memo")]
        tot = r["runtime_s"]["fit_score_per_fold"]
        if fs and all(f.get("memo") for f in fs):
            score = np.mean(tot)
        elif fs:
            score = np.mean([t - (f.get("fit_s") or 0) for t, f in zip(tot, fs)])
        else:
            score = np.mean(tot) + r["runtime_s"].get("score_all_dev", 0) / 5
        dall = s0.get("all", {}).get("diff", {})
        dnt = s0.get("no_top10", {}).get("diff", {})
        L.append(f"| `{name}` | {f3(s['ap_ht']['mean'])} ± {f3(s['ap_ht']['sd'])} | {f3(po.get('ap_ht'))} | "
                 f"{f3(po.get('ap_ht_no_top10'))} | {f3(s['macro_cluster_ap']['mean'])} | "
                 f"{f3(s['ap_ht_both_nonessential']['mean'])} / {f3(s['ap_ht_mixed']['mean'])} / "
                 f"{f3(s['ap_ht_both_essential']['mean'])} | {ci(dall.get(f'{name}-ref_best'))} | "
                 f"{ci(dall.get(f'{name}-ref_gls'))} | {ci(dnt.get(f'{name}-ref_best'))} | "
                 f"{f3(np.mean(fit)) if fit else '—'} | {score:.1f} | "
                 f"{[f.get('chosen_steps') for f in fs] if fs else '—'} |")
    if s0:
        L += ["", f"Reference: ref_best − GLS pooled OOF Δ {ci(s0['all']['diff'].get('ref_best-ref_gls'))}; no-top10 "
              f"{ci(s0['no_top10']['diff'].get('ref_best-ref_gls'))}. Pooled-OOF macro per-cluster AP: " +
              ", ".join(f"{k} {v:.3f}" for k, v in s0.get("macro_cluster_ap", {}).items()), ""]
        dcos = {k: v for k, v in s0["all"]["diff"].items() if k.endswith("-identity_cos")}
        if dcos:
            L += ["First-order learned metrics vs their initialisation (identity cosine), pooled OOF: " +
                  "; ".join(f"`{k}` {ci(v)}" for k, v in dcos.items()), ""]
    # seeds
    seeds_rows = []
    for name in ORDER:
        vals = [load(name, sd) for sd in SEEDS]
        if sum(v is not None for v in vals) > 1:
            seeds_rows.append((name, vals))
    if seeds_rows:
        L += ["## Seed repeats (HT-AP fold mean; Δ = pooled-OOF bootstrap per seed)", "",
              "| scorer | " + " | ".join(f"seed {s}" for s in SEEDS) + " | mean |", "|---|" + "---|" * (len(SEEDS) + 1)]
        for name, vals in seeds_rows:
            xs = [v["summary"]["ap_ht"]["mean"] if v else np.nan for v in vals]
            L.append(f"| `{name}` | " + " | ".join(f3(x) for x in xs) + f" | {f3(np.nanmean(xs))} |")
        L += ["", "| comparison | " + " | ".join(f"seed {s}" for s in SEEDS) + " |", "|---|" + "---|" * len(SEEDS)]
        names = [n for n, _ in seeds_rows if not n.startswith("ref_")]
        for n in names:
            for ref in ("ref_best", "ref_gls"):
                for sub in ("all", "no_top10"):
                    row = [ci(cmp["seeds"].get(str(sd), {}).get(sub, {}).get("diff", {}).get(f"{n}-{ref}"))
                           for sd in SEEDS]
                    L.append(f"| `{n}` − {ref} ({sub}) | " + " | ".join(row) + " |")
        L.append("")
    # controls
    ctl = sorted(OUT.glob("control_shuffle_*.json"))
    if ctl:
        L += ["## Training-label shuffle control (all labels permuted before fitting; true held-fold labels)", "",
              "| control | mean HT-AP | HT prevalence | identity (init) HT-AP | steps per fold |", "|---|---|---|---|---|"]
        for p in ctl:
            c = json.loads(p.read_text())
            init = load(f"identity_{c['output']}", SEEDS[0])
            L.append(f"| `{c['tag']}` | {c['mean_ap_ht']:.3f} | {c['mean_prevalence']:.4f} | "
                     f"{f3(init['summary']['ap_ht']['mean']) if init else '—'} | "
                     f"{[f.get('chosen_steps') for f in c['fit_summary']]} |")
        L.append("")
    L.append(FINDINGS if extra_text is None else extra_text)
    (OUT / "README.md").write_text("\n".join(L) + "\n")


FINDINGS = """## Findings (written after the runs; SEEDS[0] ladder, best learned config L1line on SEEDS[1..4])

1. **Sanity.** `identity_cos` = spec_k20_t0.1_std (0.365) and `identity_rowzso` = the Phase-A best (0.435, pooled-OOF Δ
   vs cached layer 0.000 [0.000, 0.000]) through the same code path; `EmbeddingEngine` reproduces src.layers /
   layers_ext on a toy to 1e-5 (tests).
2. **Ladder: no rung gains.** First order: L1 cell-line weights 0.366, L1 spectral filter 0.363, L2 d=32/64/128
   0.365/0.365/0.364, L2 d=64 InfoNCE 0.365 vs identity 0.365. L3 (second order on the learned embedding): 0.432–0.435 vs
   0.435; every pooled-OOF Δ vs the Phase-A best is within ±0.003 with CIs straddling 0 (e.g. L1line_rowzso +0.001
   [−0.004, +0.007]). Without the top-10 clusters (small/medium complexes) the learned L3 scores are equal as well
   (Δ −0.006..+0.005; L1eig_rowzso slightly worse, −0.006 [−0.013, −0.001]). Side observation: on the no-top10
   pairs the plain first-order base already equals the second-order best (identity_cos − ref_best +0.004 [−0.031,
   +0.036]; macro per-cluster AP 0.371 vs 0.341), so second order helps only the large dense complexes and supervision
   does not change that. The capacity ladder was stopped at L2 (no gain at L1 -> L2 already flat; d=128 slightly worse).
3. **Why.** The inner validation split shows the pattern directly: training loss falls (L2 BCE 0.57 -> 0.09, i.e. the
   ~650 training genes are memorised), validation AP on unseen clusters stays at its identity value (±0.003); with a
   large learning rate it collapses (0.47 -> 0.27, superseded first attempt, see below). Early stopping therefore picks
   0–220 steps of tiny updates and the fitted maps stay ≈ identity. With ~640 genes / ~1,900 positives per training fold
   (≈ 200 clusters in total) there is not enough complex diversity to learn a transferable re-weighting of 1,340
   whitened coordinates; the label-free whitening + second-order already captures what transfers.
4. **Seeds 1–4 (L1line):** HT-AP equal to identity to 3 decimals on first order and within ±0.001 of the Phase-A
   best on L3; no seed shows a Δ vs ref_best whose CI excludes 0.
5. **Controls.** Training-label shuffle: L2d64 cos 0.360, L2d64 rowzso 0.423, L1line cos 0.365 vs initialisation
   0.365 / 0.435 / 0.365 -> the learned metric never beats its initialisation without real labels (pass). Toy with
   planted pair structure in a low-variance subspace: L2 raises cluster-CV HT-AP from ≈0.05 to ≈0.27 on held-out
   genes/complexes and concentrates the metric on the planted subspace; L1 and shuffled training do not (tests).
6. **Runtime (8-core laptop, CPU torch float32):** fit 7–25 s per fold (3 λ × early-stopped inner runs + refit);
   first-order scoring 0.2–0.4 s per fold (embed all 18,434 genes, score test pairs); L3 scoring 17–49 s per fold
   (genome-wide neighbours + exact second-order row moments; ≈ the Phase-A best's 23 s, machine shared with another
   agent's jobs).

**Verdict:** supervision through a learned first-order metric does not help, neither for first-order scores nor as the
base of the second-order score, and not on small complexes. Recommendation: keep the label-free
rowz[socos_q0.25[spec_k20_t0.1_std]] as the primary; close Phase C (negative result).

Process notes: a first L2d64 run (commit 952b265, lr 1e-2, no calibration warm-up, per-pair gathering; 536 s) gave
0.364 and was superseded (same tag, overwritten; both trials are in results/trials.jsonl); an L1line run of that
version was aborted (start record without end). Probes of training dynamics on fold-0 training pairs only (inner
validation, no test-fold metric) set the learning rates (L1 1e-3, L2 2e-4) before the ladder was run.
"""

def write_readme_default():
    write_readme(FINDINGS)


if __name__ == "__main__":
    write_readme(FINDINGS)
