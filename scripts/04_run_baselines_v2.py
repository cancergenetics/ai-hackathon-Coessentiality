"""Baselines through the v2 evaluation (src/evaluate.py) on the DEV universe only.

1. All baseline variants (src.scorers.BASELINE_VARIANTS: Pearson/Spearman signed|abs; GLS {marginalise, mean-impute}
   x {olfactory-PC removal off, on} x {signed t, two-sided -log10 p}) on the §3.3 cluster-grouped 5-fold dev CV,
   SEEDS[0], with pooled-dev cluster bootstrap (1,000) -> results/baselines_v2/<variant>_cluster_seed0.json.
2. Best variant per family (pearson / spearman / gls) = highest mean fold HT-weighted AP (primary metric) at
   SEEDS[0] -> results/baselines_v2/best_variants.json (used by scripts/final_eval.py).
3. Best variants: SEEDS[1:] on the cluster scheme, and the secondary schemes (component, gene = C3, random pair)
   at SEEDS[0].
4. README.md table (generated).
Every call is one logged trial in results/trials.jsonl.

Usage: ./.env/bin/python scripts/04_run_baselines_v2.py [--allow-dirty] [--readme-only]
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np  # noqa: E402

from src import evaluate, scorers  # noqa: E402
from src.config import RESULTS, ROOT, SEEDS  # noqa: E402

OUT = RESULTS / "baselines_v2"
FAMILIES = ("pearson", "spearman", "gls")


def family(v):
    return v.split("_")[0]


def load(tag):
    return json.loads((OUT / f"{tag}.json").read_text())


def run(allow_dirty):
    subprocess.run(["sh", str(ROOT / "scripts" / "check_data.sh")], check=True, stdout=subprocess.DEVNULL)
    from src.universe import load_dev_universe
    u = load_dev_universe()
    mat = scorers.real_matrix()
    for v in scorers.BASELINE_VARIANTS:
        evaluate.run_dev_cv(scorers.make_baseline(v, mat), seed=SEEDS[0], universe=u, n_boot_pooled=1000,
                            out_dir=OUT, allow_dirty=allow_dirty, extra=dict(grid="baselines_v2"))
    best = {}
    for fam in FAMILIES:
        cands = [v for v in scorers.BASELINE_VARIANTS if family(v) == fam]
        means = {v: load(f"{v}_cluster_seed{SEEDS[0]}")["summary"]["ap_ht"]["mean"] for v in cands}
        best[fam] = max(means, key=means.get)
    (OUT / "best_variants.json").write_text(json.dumps(dict(
        best_variants=best, criterion="max mean fold HT-weighted AP, cluster-grouped dev CV, SEEDS[0]",
        n_variants_tried={f: sum(family(v) == f for v in scorers.BASELINE_VARIANTS) for f in FAMILIES}), indent=1))
    for fam, v in best.items():
        for seed in SEEDS[1:]:
            evaluate.run_dev_cv(scorers.make_baseline(v, mat), seed=seed, universe=u, out_dir=OUT,
                                allow_dirty=allow_dirty, extra=dict(grid="baselines_v2_seeds"))
        for scheme in ("component", "gene", "random"):
            evaluate.run_dev_cv(scorers.make_baseline(v, mat), seed=SEEDS[0], scheme=scheme, universe=u, out_dir=OUT,
                                allow_dirty=allow_dirty, extra=dict(grid="baselines_v2_secondary"))


def f3(x):
    return "nan" if x is None or not np.isfinite(x) else f"{x:.3f}"


def write_readme():
    best = json.loads((OUT / "best_variants.json").read_text())["best_variants"]
    L = ["# Baselines on the v2 dev evaluation", "",
         "Generated by `scripts/04_run_baselines_v2.py` (do not edit by hand). DEV pairs only (IFT never touched). "
         "Split: §3.3 cluster-grouped 5-fold CV (randomised balanced assignment), SEEDS[0]. "
         "**Primary = HT-weighted AP** (within-cluster pairs weight 1, between-cluster pairs weight K = 5; estimates the "
         "AP of the full dev universe); `rw` = uniform prevalence-reweighted AP (negatives scaled to 593,406:3,191); "
         "`raw` = unweighted fold AP. Mean ± sd over the 5 test folds. `pooled raw` = AP over all dev pairs at natural "
         "prevalence (label-free scorers); `pooled HT [95% CI]` = HT AP over all dev pairs (between-cluster weight "
         "1/f, f = dev protein fraction) with a 1,000-resample paired cluster bootstrap CI. Runtime = setup "
         "(genome-wide Σ / corrections) + scoring all dev pairs, wall clock, 8-core laptop.", "",
         "| variant | HT AP mean ± sd | rw AP | raw AP | macro-cluster AP | AP w/o largest comp. | hard-neg AP | "
         "pooled raw AP | pooled HT AP [95% CI] | runtime (s) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for v in scorers.BASELINE_VARIANTS:
        r = load(f"{v}_cluster_seed{SEEDS[0]}")
        s, p, rt = r["summary"], r["pooled"], r["runtime_s"]
        mark = " **(best)**" if v in best.values() else ""
        L.append(f"| {v}{mark} | {s['ap_ht']['mean']:.3f} ± {s['ap_ht']['sd']:.3f} | {s['ap_reweighted']['mean']:.3f} | "
                 f"{s['ap_raw']['mean']:.3f} | {s['macro_cluster_ap']['mean']:.3f} | "
                 f"{s['ap_ht_no_largest_component']['mean']:.3f} | {s['ap_ht_hard_neg']['mean']:.3f} | {p['ap_raw']:.3f} | "
                 f"{p['ap_ht']:.3f} [{p['ap_ht_ci'][0]:.3f}, {p['ap_ht_ci'][1]:.3f}] | "
                 f"{rt['setup'] + rt['score_all_dev']:.1f} |")
    L += ["", "Essentiality strata (HT AP, mean over folds; common-essential = effect < -0.5 in ≥ 50% of models):", "",
          "| variant | both non-essential | mixed | both essential | HT P@R0.1 | HT P@R0.25 | HT P@R0.5 |", "|---|---|---|---|---|---|---|"]
    for v in scorers.BASELINE_VARIANTS:
        s = load(f"{v}_cluster_seed{SEEDS[0]}")["summary"]
        L.append(f"| {v} | {f3(s['ap_ht_both_nonessential']['mean'])} | {f3(s['ap_ht_mixed']['mean'])} | "
                 f"{f3(s['ap_ht_both_essential']['mean'])} | {f3(s['ht_P@R0.1']['mean'])} | {f3(s['ht_P@R0.25']['mean'])} | "
                 f"{f3(s['ht_P@R0.5']['mean'])} |")
    L += ["", "## Best variant per baseline (selected on dev, SEEDS[0], primary metric)", "",
          "| family | best variant | HT AP per seed (mean over folds) | mean ± sd over seeds |", "|---|---|---|---|"]
    for fam, v in best.items():
        ms = [load(f"{v}_cluster_seed{s}")["summary"]["ap_ht"]["mean"] for s in SEEDS]
        L.append(f"| {fam} | {v} | " + ", ".join(f"{m:.3f}" for m in ms) + f" | {np.mean(ms):.3f} ± {np.std(ms, ddof=1):.3f} |")
    L += ["", "Secondary splits (dev pairs only, SEEDS[0]; HT AP for component grouping uses component-level weights; "
          "C3/random have equal inclusion probability so weights are 1):", "",
          "| variant | cluster (primary) | strict component | C3 protein-disjoint | random pair (leaky) |", "|---|---|---|---|---|"]
    for v in best.values():
        cells = [load(f"{v}_{sch}_seed{SEEDS[0]}")["summary"]["ap_ht"] for sch in ("cluster", "component", "gene", "random")]
        L.append(f"| {v} | " + " | ".join(f"{c['mean']:.3f} ± {c['sd']:.3f}" for c in cells) + " |")
    r0 = load(f"{best['gls']}_cluster_seed{SEEDS[0]}")
    L += ["", "Fold sizes, cluster CV SEEDS[0] (test pos/neg): " +
          "; ".join(f"f{d['fold']} {d['test_pos']}/{d['test_neg']}" for d in r0["split"]["stats"]) +
          f". Dev universe: {r0['counts']['n_pos']} pos / {r0['counts']['n_neg']} neg, {r0['counts']['n_proteins']} "
          f"proteins, {r0['counts']['n_clusters']} clusters.", "",
          "Notes:", "",
          "- GLS NaN protocols: `gls_*` = exact marginalisation (Σ from the 17,082 genes without NaN; each pair scored on "
          "the models observed for both genes with Σ[S,S] — i.e. a per-pair literal cell-line drop); `gls_impute_*` = "
          "gene-mean imputation, Σ from all genes. The literal Wainberg protocol (drop every model with any NaN) "
          "leaves 6 of 1,361 models for the scorable genes and was not run.",
          "- `_or` = Wainberg olfactory-receptor 4-PC removal (KY-only models lacking OR guides excluded, last 4 models "
          "dropped).",
          "- Selection used only the primary metric at SEEDS[0]; other seeds/schemes were run only for the selected "
          "variants. Label-free scores do not depend on the fold seed, so seed repeats measure split variance only.", ""]
    (OUT / "README.md").write_text("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-dirty", action="store_true")
    ap.add_argument("--readme-only", action="store_true")
    a = ap.parse_args()
    if not a.readme_only:
        run(a.allow_dirty)
    write_readme()


if __name__ == "__main__":
    main()
